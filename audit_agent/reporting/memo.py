"""Writing the approved memo out as a Word document."""

from __future__ import annotations

import logging
from datetime import date
from pathlib import Path

from docx import Document

logger = logging.getLogger(__name__)


def write_memo_docx(
    memo_text: str,
    output_path: Path,
    client_name: str,
    vendor: str,
    reviewer_decision: str,
    evidence_citations: list[str] | None = None,
) -> Path:
    """Render a memo with its provenance footer.

    The citations and reviewer decision are written into the document itself so
    the deliverable carries its own audit trail rather than relying on logs.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)

    document = Document()
    document.add_heading("Audit Risk Assessment Memo", level=1)
    document.add_paragraph(f"Engagement: {client_name}")
    document.add_paragraph(f"Vendor under review: {vendor}")
    document.add_paragraph(f"Date prepared: {date.today().isoformat()}")
    document.add_paragraph(f"Reviewer decision: {reviewer_decision}")

    document.add_heading("Memo", level=2)
    for line in memo_text.split("\n"):
        if line.strip():
            document.add_paragraph(line)

    if evidence_citations:
        document.add_heading("Evidence Sources", level=2)
        for citation in evidence_citations:
            document.add_paragraph(citation, style="List Bullet")

    document.add_paragraph(
        "\nGenerated by an AI-assisted workflow with human review. "
        "Subject to engagement partner sign-off before filing."
    )

    document.save(str(output_path))
    logger.info("Memo written to %s", output_path)
    return output_path
